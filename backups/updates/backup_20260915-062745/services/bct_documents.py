"""Generowanie dokumentów PDF dla analiz BCT."""

from __future__ import annotations

from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def build_bct_report_pdf(result, *, font_regular="Helvetica", font_bold="Helvetica-Bold"):
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=40, rightMargin=40, topMargin=40, bottomMargin=40)
    styles = getSampleStyleSheet()
    title = ParagraphStyle("BCTReport", parent=styles["Title"], fontName=font_bold, fontSize=18, textColor=colors.HexColor("#123B69"))
    body = ParagraphStyle("BCTBody", parent=styles["Normal"], fontName=font_regular, fontSize=10, leading=14)
    rows = [["Parametr", "Wartość"], ["BCT nominalne", f"{result.get('bct', 0):.1f} kg"], ["Bezpieczne BCT", f"{result.get('safe_bct', 0):.1f} kg"], ["Maks. warstwy", str(result.get("max_safe_layers", "-"))], ["Ryzyko", str(result.get("risk", "-"))], ["Status", str(result.get("approval", "-"))]]
    table = Table(rows, colWidths=[220, 280])
    table.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#123B69")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("FONTNAME", (0, 0), (-1, -1), font_regular), ("GRID", (0, 0), (-1, -1), .4, colors.HexColor("#CBD5E1")), ("PADDING", (0, 0), (-1, -1), 7)]))
    lang = result.get("language", "PL")
    headings = {"PL": "RAPORT BCT", "EN": "BCT REPORT", "PL/EN": "RAPORT BCT / BCT REPORT"}
    notes = {"PL": "Raport wygenerowany przez Kalkulator. Konstrukcja wymaga zatwierdzenia przed produkcją.", "EN": "Report generated by the Calculator. The construction requires approval before production.", "PL/EN": "Raport wygenerowany przez Kalkulator / Report generated by the Calculator. Konstrukcja wymaga zatwierdzenia przed produkcją / The construction requires approval before production."}
    doc.build([Paragraph(headings.get(lang, headings["PL"]), title), Spacer(1, 12), table, Spacer(1, 18), Paragraph(notes.get(lang, notes["PL"]), body)])
    return buffer.getvalue()


def build_bct_text_document_pdf(title_text, lines, *, font_regular="Helvetica", font_bold="Helvetica-Bold"):
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=40, rightMargin=40, topMargin=40, bottomMargin=40)
    styles = getSampleStyleSheet()
    title = ParagraphStyle("BCTDocTitle", parent=styles["Title"], fontName=font_bold, fontSize=17, textColor=colors.HexColor("#123B69"))
    body = ParagraphStyle("BCTDocBody", parent=styles["Normal"], fontName=font_regular, fontSize=10, leading=15)
    doc.build([Paragraph(escape(str(title_text)), title), Spacer(1, 14)] + [Paragraph(escape(str(line)), body) for line in lines])
    return buffer.getvalue()
